<?php

declare(strict_types=1);

namespace Tests\Functional\Api;

use DAMA\DoctrineTestBundle\PHPUnit\SkipDatabaseRollback;
use DateTimeImmutable;
use Doctrine\DBAL\Connection;
use Doctrine\ORM\EntityManagerInterface;
use Doctrine\Persistence\ConnectionRegistry;
use Equipment\Application\Port\Outbound\EquipmentCsvRendererPort;
use Equipment\Infrastructure\Persistence\Doctrine\Record\EquipmentRecord;
use Facility\Infrastructure\Persistence\Doctrine\Record\FacilityRecord;
use Organization\Infrastructure\Persistence\Doctrine\Record\{OrganizationMemberRecord, OrganizationMemberRoleRecord, OrganizationRecord, OrganizationRoleRecord, PlanRecord};
use PHPUnit\Framework\Attributes\DataProvider;
use RuntimeException;
use Shared\Application\Port\Outbound\{CurrentActorPort, UuidGeneratorPort};
use Shared\Infrastructure\Messaging\Outbox\TransactionalEventDispatcher;
use Symfony\Bundle\FrameworkBundle\KernelBrowser;
use Symfony\Bundle\FrameworkBundle\Test\WebTestCase;
use Symfony\Component\Messenger\Bridge\Doctrine\Transport\{DoctrineTransport, DoctrineTransportFactory};
use Symfony\Component\Messenger\Transport\Serialization\PhpSerializer;
use Tests\Support\Auth\InteractiveTokenFactory;
use Tests\Support\Database\RootCommitDatabaseIsolationTrait;
use User\Infrastructure\Persistence\Doctrine\Record\UserRecord;

/** Actual GET downloads must replay identical generated bytes and enqueue exactly one owning main audit event. @category Functional Test */
#[SkipDatabaseRollback]
final class HttpIdempotencyOperationalExportApiTest extends WebTestCase
{
  use RootCommitDatabaseIsolationTrait;

  private const string USER = 'ee000000-0000-4000-8000-000000000001';

  private const string ORGANIZATION = 'ee000000-0000-4000-8000-000000000002';

  private const string ROLE = 'ee000000-0000-4000-8000-000000000003';

  private const string EQUIPMENT = 'ee000000-0000-4000-8000-000000000004';

  private const string FACILITY = 'ee000000-0000-4000-8000-000000000006';

  /**
   * @return iterable<string, array{string, string}>
   */
  public static function downloads(): iterable
  {
    yield 'equipment csv' => ['/equipment/export', 'text/csv'];
    yield 'equipment report pdf' => ['/equipment/' . self::EQUIPMENT . '/report', 'application/pdf'];
    yield 'equipment labels pdf' => ['/equipment/labels?ids[]=' . self::EQUIPMENT, 'application/pdf'];
    yield 'facility csv' => ['/facilities/export?search=original', 'text/csv'];
  }

  #[DataProvider('downloads')]
  public function testDownloadReplaysOriginalBytesAndFilenameButRechecksCurrentReadRights(string $suffix, string $contentType): void
  {
    $client = self::createClient();
    $this->replaceMainOutboxWithRealSqlTransport();
    $this->seed($client);
    $headers = ['HTTP_IDEMPOTENCY_KEY' => 'original-export', 'HTTP_ACCEPT' => $contentType];
    $uri = '/api/organizations/' . self::ORGANIZATION . $suffix;
    $mainBefore = $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'");
    self::assertIsInt($mainBefore);
    $client->request('GET', $uri, server: $headers);
    self::assertResponseStatusCodeSame(200);
    self::assertStringContainsString($contentType, $client->getResponse()->headers->get('Content-Type') ?? '');
    $original = $client->getInternalResponse()->getContent();
    self::assertNotSame('', $original);
    if ('application/pdf' === $contentType) {
      self::assertStringStartsWith('%PDF-', $original);
    }
    $disposition = $client->getResponse()->headers->get('Content-Disposition');
    self::assertSame($mainBefore + 1, $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'"));
    self::assertSame(1, $this->main()->fetchOne("SELECT COUNT(*) FROM http_idempotency_receipts WHERE state = 'completed'"));
    $this->main()->executeStatement('UPDATE equipment SET brand = ?, name = ? WHERE id = ?', ['later-equipment-brand', 'later-equipment', self::EQUIPMENT]);
    $this->main()->executeStatement('UPDATE facilities SET name = ? WHERE id = ?', ['later-facility', self::FACILITY]);

    $client->request('GET', $uri, server: $headers);
    self::assertResponseStatusCodeSame(200);
    self::assertResponseHeaderSame('Idempotency-Replayed', 'true');
    self::assertSame($original, $client->getInternalResponse()->getContent());
    self::assertSame($disposition, $client->getResponse()->headers->get('Content-Disposition'));
    self::assertSame($mainBefore + 1, $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'"));
    $this->main()->executeStatement('UPDATE organization_roles SET permissions = ? WHERE id = ?', ['["organization.equipment.write","organization.facilities.write"]', self::ROLE]);
    $client->request('GET', $uri, server: $headers);
    self::assertResponseStatusCodeSame(403);
    self::assertFalse($client->getResponse()->headers->has('Idempotency-Replayed'));
    self::assertNotSame($original, $client->getInternalResponse()->getContent());
    self::assertSame($mainBefore + 1, $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'"));
  }

  public function testCsvRenderingFailureRollsBackItsAuditAndNeverCompletesTheReceipt(): void
  {
    $client = self::createClient();
    $this->replaceMainOutboxWithRealSqlTransport();
    $this->seed($client);
    $renderer = $this->createStub(EquipmentCsvRendererPort::class);
    $renderer->method('render')->willThrowException(new RuntimeException('CSV rendering unavailable.'));
    self::getContainer()->set(EquipmentCsvRendererPort::class, $renderer);
    $before = $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'");
    $client->request('GET', '/api/organizations/' . self::ORGANIZATION . '/equipment/export', server: ['HTTP_IDEMPOTENCY_KEY' => 'failed-render']);
    self::assertResponseStatusCodeSame(500);
    self::assertSame($before, $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'"));
    self::assertSame(0, $this->main()->fetchOne("SELECT COUNT(*) FROM http_idempotency_receipts WHERE state = 'completed'"));
    self::assertSame('pending', $this->main()->fetchOne('SELECT state FROM http_idempotency_receipts'));
  }

  public function testReportReplayRechecksTheCurrentPlanBeforeOpeningTheSavedPdf(): void
  {
    $client = self::createClient();
    $this->replaceMainOutboxWithRealSqlTransport();
    $this->seed($client);
    $uri = '/api/organizations/' . self::ORGANIZATION . '/equipment/' . self::EQUIPMENT . '/report';
    $headers = ['HTTP_IDEMPOTENCY_KEY' => 'paid-report', 'HTTP_ACCEPT' => 'application/pdf'];
    $client->request('GET', $uri, server: $headers);
    self::assertResponseStatusCodeSame(200);
    $original = $client->getInternalResponse()->getContent();
    self::assertStringStartsWith('%PDF-', $original);
    $before = $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'");
    $basicPlan = $this->main()->fetchOne("SELECT id FROM plans WHERE plan_key NOT IN ('pro', 'max') ORDER BY sort_order LIMIT 1");
    self::assertIsString($basicPlan);
    $this->main()->executeStatement('UPDATE organizations SET plan_id = ? WHERE id = ?', [$basicPlan, self::ORGANIZATION]);

    $client->request('GET', $uri, server: $headers);
    self::assertResponseStatusCodeSame(403);
    self::assertNotSame($original, $client->getInternalResponse()->getContent());
    self::assertFalse($client->getResponse()->headers->has('Idempotency-Replayed'));
    self::assertSame($before, $this->main()->fetchOne("SELECT COUNT(*) FROM messenger_messages WHERE queue_name = 'main_outbox'"));
  }

  private function replaceMainOutboxWithRealSqlTransport(): void
  {
    $registry = $this->createStub(ConnectionRegistry::class);
    $registry->method('getConnection')->willReturn($this->main());
    $transport = new DoctrineTransportFactory($registry)->createTransport('doctrine://main?queue_name=main_outbox&auto_setup=false', ['use_notify' => false], new PhpSerializer());
    self::assertInstanceOf(DoctrineTransport::class, $transport);
    $transport->setup();
    $ids = self::getContainer()->get(UuidGeneratorPort::class);
    $actor = self::getContainer()->get(CurrentActorPort::class);
    self::assertInstanceOf(UuidGeneratorPort::class, $ids);
    self::assertInstanceOf(CurrentActorPort::class, $actor);
    $events = new TransactionalEventDispatcher($this->main(), $transport, $ids, $actor);
    self::getContainer()->set('equipment.export_events', $events);
    self::getContainer()->set('facility.export_events', $events);
  }

  private function main(): Connection
  {
    $connection = self::getContainer()->get('doctrine.dbal.main_connection');
    self::assertInstanceOf(Connection::class, $connection);

    return $connection;
  }

  private function seed(KernelBrowser $client): void
  {
    $client->disableReboot();
    $auth = self::getContainer()->get('doctrine.orm.auth_entity_manager');
    $main = self::getContainer()->get('doctrine.orm.main_entity_manager');
    self::assertInstanceOf(EntityManagerInterface::class, $auth);
    self::assertInstanceOf(EntityManagerInterface::class, $main);
    $now = new DateTimeImmutable();
    $user = new UserRecord();
    $user->id = self::USER;
    $user->username = 'idempotency-http-test';
    $user->email = 'idempotency-http@example.test';
    $user->firstName = 'HTTP';
    $user->lastName = 'Replay';
    $user->status = 'active';
    $user->emailVerified = true;
    $user->emailOwnershipVerifiedAt = $now;
    $user->createdAt = $now;
    $auth->persist($user);
    $auth->flush();
    $organization = new OrganizationRecord();
    $organization->id = self::ORGANIZATION;
    $organization->name = 'HTTP idempotency';
    $organization->slug = 'http-idempotency-test';
    $organization->ownerUserId = 'ed000000-0000-4000-8000-000000000099';
    $organization->createdByUserId = self::USER;
    $plan = $main->getRepository(PlanRecord::class)->findOneBy(['key' => 'pro']);
    self::assertInstanceOf(PlanRecord::class, $plan);
    $organization->planId = $plan->id;
    $organization->createdAt = $now;
    $organization->updatedAt = $now;
    $main->persist($organization);
    $role = new OrganizationRoleRecord();
    $role->id = self::ROLE;
    $role->organization = $organization;
    $role->name = 'http-replay-role';
    $role->permissions = ['*'];
    $role->createdAt = $now;
    $main->persist($role);
    $member = new OrganizationMemberRecord();
    $member->id = 'ed000000-0000-4000-8000-000000000005';
    $member->organization = $organization;
    $member->userId = self::USER;
    $member->isActive = true;
    $member->joinedAt = $now;
    $main->persist($member);
    $assignment = new OrganizationMemberRoleRecord();
    $assignment->member = $member;
    $assignment->role = $role;
    $assignment->assignedAt = $now;
    $main->persist($assignment);
    $equipment = new EquipmentRecord();
    $equipment->id = self::EQUIPMENT;
    $equipment->organizationId = self::ORGANIZATION;
    $equipment->type = 'fire_extinguisher';
    $equipment->status = 'in_stock';
    $equipment->recordStatus = 'published';
    $equipment->brand = 'original-equipment-brand';
    $equipment->name = 'original-equipment';
    $facility = new FacilityRecord();
    $facility->id = self::FACILITY;
    $facility->organizationId = self::ORGANIZATION;
    $facility->type = 'site';
    $facility->name = 'original-facility';
    $facility->status = 'active';
    $facility->createdAt = $now;
    $facility->updatedAt = $now;
    $main->persist($facility);
    $equipment->createdAt = $now;
    $equipment->updatedAt = $now;
    $main->persist($equipment);
    $main->flush();
    $client->setServerParameter('HTTP_AUTHORIZATION', 'Bearer ' . InteractiveTokenFactory::issue(self::getContainer(), self::USER, $user->email));
  }
}
